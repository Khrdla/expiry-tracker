    async def test_pdf_export_endpoint(self):
        """Test the PDF export endpoint and get PDF content"""
        try:
            self.test_results.append("\n📄 TESTING INVENTORY SCANNING PDF EXPORT ENDPOINT:")
            
            async with self.session.get(
                f"{BACKEND_URL}/inventory-scans/export-pdf",
                headers=self.get_auth_headers()
            ) as response:
                if response.status != 200:
                    error_text = await response.text()
                    self.test_results.append(f"❌ PDF Export failed: {response.status} - {error_text}")
                    return False, None
                    
                # Get the PDF file content
                pdf_content = await response.read()
                self.test_results.append(f"✅ PDF file downloaded successfully: {len(pdf_content)} bytes")
                
                # Verify Content-Type header
                content_type = response.headers.get('content-type', '')
                if content_type == 'application/pdf':
                    self.test_results.append("✅ Correct Content-Type header (application/pdf)")
                else:
                    self.test_results.append(f"❌ Incorrect Content-Type: {content_type}")
                
                # Verify PDF is valid
                try:
                    pdf_reader = PyPDF2.PdfReader(BytesIO(pdf_content))
                    num_pages = len(pdf_reader.pages)
                    self.test_results.append(f"✅ Valid PDF file with {num_pages} pages")
                    return True, pdf_content
                except Exception as pdf_error:
                    self.test_results.append(f"❌ Invalid PDF file: {str(pdf_error)}")
                    return False, None
                
        except Exception as e:
            self.test_results.append(f"❌ PDF Export error: {str(e)}")
            return False, None
            
    async def verify_geant_theme_requirements(self, pdf_content):
        """Verify all Geant Yemen theme requirements in the PDF"""
        try:
            self.test_results.append("\n🎨 VERIFYING GEANT YEMEN THEME REQUIREMENTS:")
            
            pdf_reader = PyPDF2.PdfReader(BytesIO(pdf_content))
            all_text = ""
            
            # Extract all text from PDF
            for page in pdf_reader.pages:
                all_text += page.extract_text() + "\n"
            
            theme_compliance = 0
            total_requirements = 8
            
            # 1. Page Title Styling
            if self.theme_requirements["page_title"] in all_text:
                self.test_results.append("✅ 1. Page Title: 'Geant Hypermarket – Inventory Scanning Report' found")
                theme_compliance += 1
            else:
                self.test_results.append("❌ 1. Page Title: 'Geant Hypermarket – Inventory Scanning Report' missing")
            
            # 2. Section Titles Design
            section_pattern = re.compile(self.theme_requirements["section_title_pattern"])
            section_matches = section_pattern.findall(all_text)
            if section_matches:
                self.test_results.append(f"✅ 2. Section Titles: Found {len(section_matches)} zone section titles with correct format")
                for match in section_matches:
                    self.test_results.append(f"   - {match}")
                theme_compliance += 1
            else:
                self.test_results.append("❌ 2. Section Titles: Zone section titles with correct format not found")
            
            # 3. Table Header Styling
            headers_found = 0
            for header in self.theme_requirements["table_headers"]:
                if header in all_text:
                    headers_found += 1
            
            if headers_found == len(self.theme_requirements["table_headers"]):
                self.test_results.append("✅ 3. Table Headers: All required headers found (Item Number, Barcode, Description, Quantity Scanned)")
                theme_compliance += 1
            else:
                self.test_results.append(f"❌ 3. Table Headers: Only {headers_found}/{len(self.theme_requirements['table_headers'])} headers found")
            
            # 4. Summary Line
            summary_pattern = re.compile(self.theme_requirements["summary_pattern"])
            summary_matches = summary_pattern.findall(all_text)
            if summary_matches:
                self.test_results.append(f"✅ 4. Summary Lines: Found {len(summary_matches)} zone summaries with correct format")
                for match in summary_matches:
                    self.test_results.append(f"   - {match}")
                theme_compliance += 1
            else:
                self.test_results.append("❌ 4. Summary Lines: Zone summaries with correct format not found")
            
            # 5. Footer Design
            if self.theme_requirements["footer_text"] in all_text:
                self.test_results.append("✅ 5. Footer: 'Generated by Geant Yemen Inventory System.' found")
                theme_compliance += 1
            else:
                self.test_results.append("❌ 5. Footer: 'Generated by Geant Yemen Inventory System.' missing")
            
            # 6. Professional Layout (check for proper structure)
            if "Zone" in all_text and "Inventory Details" in all_text and "Summary:" in all_text:
                self.test_results.append("✅ 6. Professional Layout: Proper zone structure and organization detected")
                theme_compliance += 1
            else:
                self.test_results.append("❌ 6. Professional Layout: Missing proper zone structure")
            
            # 7. Page Layout Specifications (check for proper margins and formatting)
            if len(pdf_reader.pages) > 0:
                # Check if pages have content (indicating proper margins and layout)
                first_page_text = pdf_reader.pages[0].extract_text()
                if len(first_page_text.strip()) > 100:  # Reasonable content length
                    self.test_results.append("✅ 7. Page Layout: Proper content layout and margins detected")
                    theme_compliance += 1
                else:
                    self.test_results.append("❌ 7. Page Layout: Insufficient content or layout issues")
            else:
                self.test_results.append("❌ 7. Page Layout: No pages found")
            
            # 8. Geant Yemen Branding
            geant_branding_terms = ["Geant", "Hypermarket", "Yemen", "Inventory"]
            branding_found = sum(1 for term in geant_branding_terms if term in all_text)
            if branding_found >= 3:
                self.test_results.append(f"✅ 8. Geant Yemen Branding: Strong branding presence ({branding_found}/4 key terms found)")
                theme_compliance += 1
            else:
                self.test_results.append(f"❌ 8. Geant Yemen Branding: Weak branding presence ({branding_found}/4 key terms found)")
            
            # Calculate compliance percentage
            compliance_percentage = (theme_compliance / total_requirements) * 100
            self.test_results.append(f"\n📊 THEME COMPLIANCE SCORE: {theme_compliance}/{total_requirements} ({compliance_percentage:.1f}%)")
            
            if compliance_percentage >= 80:
                self.test_results.append("🎉 EXCELLENT: Geant Yemen theme requirements substantially met!")
                return True
            elif compliance_percentage >= 60:
                self.test_results.append("⚠️ GOOD: Most Geant Yemen theme requirements met, minor improvements needed")
                return True
            else:
                self.test_results.append("❌ POOR: Significant Geant Yemen theme requirements missing")
                return False
                
        except Exception as e:
            self.test_results.append(f"❌ Theme verification error: {str(e)}")
            return False
            
